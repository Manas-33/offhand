#!/usr/bin/env python3
"""Export the prompt template the Offhand app sends to the on-device model.

The app has to feed the NPU model byte-identical text to what the eval runs
saw, or a device-vs-GPU gap could just be a formatting artifact. So instead of
trusting the runtime's own chat-template rendering (the GenieX SDK stops
including the tools after its first call), the template is rendered here with
the eval's own ``build_prompt`` (same system prompt, same tool schemas, same
``apply_chat_template(..., enable_thinking=False)`` call) and shipped as an
app asset.

Only the user text varies between requests, so the render splits into a fixed
prefix and suffix around it. Every eval item is re-rendered and checked
against prefix + query + suffix before anything is written.

The tokenizer defaults to the base model: train/train_lora.py saves the base
tokenizer unchanged next to the merged checkpoint, so this is the chat template
the eval used. Re-run whenever tools.json or the system prompt changes.

Usage:
    python eval/export_app_prompt.py
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from offhand_eval.dataset import load_items, load_tools  # noqa: E402
from quantize_aimet import build_prompt  # noqa: E402  (the exact call behind the W4A16 runs)

APP_ASSET = HERE.parent / "app/android/app/src/main/assets/prompt_template.json"
MARKER = "@@OFFHAND_USER_TEXT@@"


def main() -> None:
    ap = argparse.ArgumentParser(description="Render the app's prompt template")
    ap.add_argument("--tokenizer", default="Qwen/Qwen3-0.6B",
                    help="HF id or local path; the merged checkpoint ships the base tokenizer")
    ap.add_argument("--tools", default=str(HERE / "tools.json"))
    ap.add_argument("--data", default=str(HERE / "mini_eval.jsonl"),
                    help="items used to verify the prefix/suffix split")
    ap.add_argument("--out", default=str(APP_ASSET))
    args = ap.parse_args()

    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(args.tokenizer)
    tools = load_tools(args.tools)

    full = build_prompt(tokenizer, MARKER, tools)
    if full.count(MARKER) != 1:
        raise SystemExit(f"marker appears {full.count(MARKER)} times in the render; cannot split")
    prefix, suffix = full.split(MARKER)

    items = load_items(args.data)
    for item in items:
        if build_prompt(tokenizer, item["query"], tools) != prefix + item["query"] + suffix:
            raise SystemExit(f"prefix + query + suffix does not reproduce the eval prompt for {item['id']}")

    out = {
        "_note": "Generated by eval/export_app_prompt.py. Do not edit by hand.",
        "tokenizer": args.tokenizer,
        "tools_sha256": hashlib.sha256(Path(args.tools).read_bytes()).hexdigest(),
        "prefix": prefix,
        "suffix": suffix,
    }
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")

    n_prefix = len(tokenizer(prefix, add_special_tokens=False).input_ids)
    print(f"prefix: {len(prefix)} chars, {n_prefix} tokens")
    print(f"suffix: {suffix!r}")
    print(f"verified against all {len(items)} eval items")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
